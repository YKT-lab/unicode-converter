"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const core = require("../js/combining-core.js");
const data = JSON.parse(fs.readFileSync(path.join(__dirname, "../data/combining-marks.json"), "utf8"));
const marks = core.prepareCatalogue(data);
const at = cp => marks.find(mark => mark.codepoint === cp);
assert.equal(marks.length, data.count);
assert(marks.length > 2400, "All mark categories, not just familiar Latin accents");
assert.deepEqual(Object.fromEntries(["Mn", "Mc", "Me"].map(category => [category, marks.filter(x => x.category === category).length])), data.category_counts);
assert.equal(core.codePoints("A😀\u0301"), "U+0041 U+1F600 U+0301");
assert.equal(core.codePoints(""), "");
assert.equal(core.compose("a", [at(0x301), at(0x323)]), "a\u0301\u0323");
assert.equal(core.compose("😀字\u200D", [at(0x301)]), "😀字\u200D\u0301");
assert.equal(core.compose("", [at(0x301)]), "\u0301", "Dotted circle is never inserted into result");
assert.equal(core.compose("<script>&\uD800", []), "<script>&\uD800", "Input remains text, including unmatched UTF-16");
const selected = [at(0x301), at(0x323), at(0x301)];
const moved = core.move(selected, 1, -1);
assert.equal(core.compose("a", moved), "a\u0323\u0301\u0301");
assert.equal(core.compose("a", selected), "a\u0301\u0323\u0301", "Reordering does not mutate original state");
assert.deepEqual(core.move(selected, 0, -1), selected);
assert.deepEqual(core.move(selected, 5, -1), selected);
for (const query of ["U+0301", "U+301", "0x0301", "0x301", "0301", "COMBINING ACUTE ACCENT"]) {
  assert(core.search(marks, query).some(x => x.codepoint === 0x301), query);
}
assert(core.search(marks, "U+03").every(x => x.codepoint >= 0x300 && x.codepoint <= 0x3FF));
assert(core.search(marks, "Arabic", "", "Mn").every(x => x.category === "Mn" && x.search.includes("arabic")));
assert(core.search(marks, "", "", "Me").every(x => x.category === "Me"));
assert(core.search(marks, "", "Hebr").some(x => x.codepoint === 0x5B8));
assert(core.search(marks, "", "Deva", "Mc").some(x => x.codepoint === 0x93F));
assert(core.search(marks, "", "Latn").some(x => x.script_extensions.includes("Latn")), "ScriptExtensions is searchable");
assert.equal(core.search(marks, "not_a_real_unicode_name").length, 0);
assert(at(0xFE0F), "Zero-CCC Mn variation selector must remain included");
assert(at(0xE0100), "Supplementary variation selectors remain included");
assert.throws(() => core.prepareCatalogue({...data, count: 0}));
assert.throws(() => core.prepareCatalogue({...data, marks: [{...data.marks[0], codepoint:0xD800}], count:1}));
const browser = {};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, "../js/combining-core.js"), "utf8"), browser);
assert.equal(browser.UnicodeCombiningCore.codePoints("😀\u0301"), "U+1F600 U+0301");
console.log("PASS: combining catalogue, filters, exact sequences, duplicate/reorder behavior and browser export (" + marks.length + " marks)");
